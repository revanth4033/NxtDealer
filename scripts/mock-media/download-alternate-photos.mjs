// Downloads alternate photo sets: extra Commons photos of the same model and colour as an existing set, so one
// dealer's vehicles don't have to share a cover photo. Each alternate set is one physical car.
// Run after download-photos.mjs (which rewrites ATTRIBUTION.md): node download-alternate-photos.mjs <projectRoot>
//
// Input:  scripts/mock-media/alternate-picks.json
// Output: public/mock-media/vehicles/{key}-{n}.jpg, src/mocks/vehicle-photo-alternates.ts,
//         and an "Alternate photos" section appended to public/mock-media/vehicles/ATTRIBUTION.md
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const here = new URL('.', import.meta.url).pathname
const root = process.argv[2]
if (!root) throw new Error('Usage: node download-alternate-photos.mjs <projectRoot>')
const UA = 'NxtDealerMockMedia/1.0 (local development script)'
const picks = JSON.parse(readFileSync(join(here, 'alternate-picks.json'), 'utf8'))
const outDir = join(root, 'public/mock-media/vehicles')
const raw = join(here, 'raw-alternates')
mkdirSync(raw, { recursive: true })

const credits = []
const sets = []
for (const { key, baseSet, sources } of picks) {
  const photos = []
  for (const [n, source] of sources.entries()) {
    const file = `${key}-${n + 1}.jpg`
    const dest = join(outDir, file)
    if (!existsSync(dest)) {
      const tmp = join(raw, file)
      const res = await fetch(source.thumb.replace(/\/\d+px-/, '/1280px-'), { headers: { 'User-Agent': UA } })
      if (!res.ok) throw new Error(`${res.status} for ${source.title}`)
      writeFileSync(tmp, Buffer.from(await res.arrayBuffer()))
      // Same treatment as the base photos: 768px high (or 1024px wide), centre-cropped to 1024x768.
      const { width, height } = readSize(tmp)
      execFileSync('sips', [...(width / height >= 4 / 3 ? ['--resampleHeight', '768'] : ['--resampleWidth', '1024']), tmp, '--out', dest], { stdio: 'ignore' })
      execFileSync('sips', ['--cropToHeightWidth', '768', '1024', '-s', 'formatOptions', 'low', dest], { stdio: 'ignore' })
      await new Promise((r) => setTimeout(r, 1000))
    }
    photos.push(`/mock-media/vehicles/${file}`)
    credits.push({ file, title: source.title.replace(/^File:/, ''), author: source.artist || 'Unknown', license: source.license, page: source.page })
  }
  sets.push({ key, baseSet, photos })
  console.log(key.padEnd(32), photos.length)
}
rmSync(raw, { recursive: true, force: true })

function readSize(path) {
  const out = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', path], { encoding: 'utf8' })
  return { width: Number(out.match(/pixelWidth: (\d+)/)[1]), height: Number(out.match(/pixelHeight: (\d+)/)[1]) }
}

const ts = `/**
 * Alternate photo sets (generated by scripts/mock-media/download-alternate-photos.mjs — do not edit by hand).
 * Each is another car of the same model and colour as \`baseSet\`, used only to give a dealer's vehicles
 * distinct cover photos. They never affect which vehicles exist, are published or have reels.
 */
export interface AlternatePhotoSet {
  key: string
  /** The VEHICLE_PHOTO_SETS key this set can stand in for (same model, same colour). */
  baseSet: string
  photos: string[]
}

export const ALTERNATE_PHOTO_SETS: AlternatePhotoSet[] = ${JSON.stringify(sets, null, 2)}
`
writeFileSync(join(root, 'src/mocks/vehicle-photo-alternates.ts'), ts)

// Replace any previous alternates section so re-running stays idempotent.
const attributionPath = join(outDir, 'ATTRIBUTION.md')
const MARKER = '\n## Alternate photos\n'
const base = readFileSync(attributionPath, 'utf8').split(MARKER)[0].trimEnd()
const escape = (s) => s.replace(/\|/g, '\\|')
const section = [
  MARKER.trim(),
  '',
  'Additional photos of the same model and colour, used so one dealer’s vehicles don’t share a cover photo.',
  '',
  '| File | Original | Author | Licence |',
  '| --- | --- | --- | --- |',
  ...credits.map((c) => `| ${c.file} | [${escape(c.title)}](${c.page}) | ${c.author.replace(/\|/g, '/')} | ${c.license} |`),
].join('\n')
writeFileSync(attributionPath, `${base}\n\n${section}\n`)
console.log('alternate photos:', credits.length)
