import type { EntityId, ISODateString, ListParams } from './common'

export type DealerStatus = 'active' | 'pending' | 'suspended' | 'inactive'

export type DealerPlan = 'free' | 'growth' | 'pro'

export type DealerVerificationStatus = 'verified' | 'in_review' | 'unverified' | 'rejected'

export interface DealerLocation {
  city: string
  state: string
}

export interface Dealer {
  id: EntityId
  businessName: string
  ownerName: string
  email: string
  phone: string
  location: DealerLocation
  status: DealerStatus
  plan: DealerPlan
  verificationStatus: DealerVerificationStatus
  /** Number of vehicles currently listed on the marketplace. */
  activeListings: number
  /** Number of AI reels generated by this dealer. */
  reelsGenerated: number
  joinedAt: ISODateString
  lastActiveAt: ISODateString
}

export type DealerSortField = 'businessName' | 'joinedAt' | 'lastActiveAt' | 'activeListings'

export interface DealerListParams extends ListParams<DealerSortField> {
  status?: DealerStatus
  plan?: DealerPlan
}
